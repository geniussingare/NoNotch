import AppKit
import Observation

/// Recent clipboard entries. Polls `changeCount` (the only API macOS offers),
/// skipping password-manager and transient content.
@MainActor
@Observable
final class ClipboardHistory {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }

    struct Entry: Identifiable, Equatable {
        let id = UUID()
        let content: Content
        let date: Date
        let sourceApp: NSImage?
    }

    private static let limit = 30
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private(set) var entries: [Entry] = []

    @ObservationIgnored private let pasteboard = NSPasteboard.general
    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    func start() {
        guard timer == nil else { return }
        changeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.25
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func copy(_ entry: Entry) {
        pasteboard.clearContents()
        switch entry.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        }
        changeCount = pasteboard.changeCount
        // Move to front.
        entries.removeAll { $0.id == entry.id }
        entries.insert(Entry(content: entry.content, date: Date(), sourceApp: entry.sourceApp), at: 0)
    }

    func remove(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clear() {
        entries.removeAll()
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes), let content = readContent() else { return }

        entries.removeAll { $0.content == content }
        let source = NSWorkspace.shared.frontmostApplication?.icon
        entries.insert(Entry(content: content, date: Date(), sourceApp: source), at: 0)
        if entries.count > Self.limit { entries.removeLast(entries.count - Self.limit) }
    }

    private func readContent() -> Content? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let image = NSImage(pasteboard: pasteboard), pasteboard.availableType(from: [.png, .tiff]) != nil {
            return .image(image)
        }
        if let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            return .text(text)
        }
        return nil
    }
}
